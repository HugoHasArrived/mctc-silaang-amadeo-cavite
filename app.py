@app.route('/staff/cases/add', methods=['GET','POST'])
@staff_required
def add_case():
    if request.method == 'POST':
        values = (request.form.get('case_number','').strip(), request.form.get('title','').strip(), request.form.get('parties','').strip(), request.form.get('case_type','').strip(), request.form.get('status','Pending').strip(), request.form.get('summary','').strip(), request.form.get('public_summary','').strip(), now(), now())
        if not values[0] or not values[1]:
            flash('Case number and title are required.', 'danger')
            return render_template('add_case.html')
        connection = db()
        try:
            cursor = connection.execute('INSERT INTO cases(case_number,title,parties,case_type,status,summary,public_summary,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?,?)', values)
            connection.commit()
            case_id = cursor.lastrowid
            audit('CREATE_CASE', values[0])
            flash('Case created.', 'success')
            return redirect(url_for('staff_case', case_id=case_id))
        except sqlite3.IntegrityError:
            connection.rollback()
            flash('That case number already exists.', 'danger')
        finally:
            connection.close()
    return render_template('add_case.html')

