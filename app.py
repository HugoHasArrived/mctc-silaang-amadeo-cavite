def now():
    return datetime.utcnow().isoformat()

def db():
    connection = sqlite3.connect(DATABASE)
    connection.row_factory = sqlite3.Row
    connection.execute('PRAGMA foreign_keys = ON')
    return connection

def hash_password(password):
    salt = secrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac('sha256', password.encode(), salt.encode(), 150000).hex()
    return salt + '$' + digest

def check_password(password, stored):
    try:
        salt, digest = stored.split('$', 1)
        actual = hashlib.pbkdf2_hmac('sha256', password.encode(), salt.encode(), 150000).hex()
        return secrets.compare_digest(actual, digest)
    except ValueError:
        return False

def init_db():
    connection = db()
    connection.executescript('''
    CREATE TABLE IF NOT EXISTS staff (id INTEGER PRIMARY KEY AUTOINCREMENT, username TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'staff', active INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS cases (id INTEGER PRIMARY KEY AUTOINCREMENT, case_number TEXT UNIQUE NOT NULL, title TEXT NOT NULL, parties TEXT NOT NULL DEFAULT '', case_type TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'Pending', summary TEXT NOT NULL DEFAULT '', public_summary TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS hearings (id INTEGER PRIMARY KEY AUTOINCREMENT, case_id INTEGER NOT NULL, hearing_date TEXT NOT NULL, hearing_time TEXT NOT NULL DEFAULT '', courtroom TEXT NOT NULL DEFAULT '', purpose TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'Scheduled', FOREIGN KEY(case_id) REFERENCES cases(id) ON DELETE CASCADE);
    CREATE TABLE IF NOT EXISTS notices (id INTEGER PRIMARY KEY AUTOINCREMENT, title_en TEXT NOT NULL, title_fil TEXT NOT NULL, body_en TEXT NOT NULL, body_fil TEXT NOT NULL, notice_type TEXT NOT NULL DEFAULT 'General', published INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS documents (id INTEGER PRIMARY KEY AUTOINCREMENT, case_id INTEGER NOT NULL, filename TEXT NOT NULL, display_name TEXT NOT NULL, public_access INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL, FOREIGN KEY(case_id) REFERENCES cases(id) ON DELETE CASCADE);
    CREATE TABLE IF NOT EXISTS audit_log (id INTEGER PRIMARY KEY AUTOINCREMENT, username TEXT NOT NULL, action TEXT NOT NULL, target TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL);
    ''')
    staff = connection.execute('SELECT id FROM staff WHERE username=?', ('admin',)).fetchone()
    if staff is None:
        connection.execute('INSERT INTO staff(username,password_hash,role,active,created_at) VALUES(?,?,?,?,?)', ('admin', hash_password('admin123'), 'admin', 1, now()))
    connection.commit()
    connection.close()

def audit(action, target=''):
    connection = db()
    connection.execute('INSERT INTO audit_log(username,action,target,created_at) VALUES(?,?,?,?)', (session.get('username','system'), action, target, now()))
    connection.commit()
    connection.close()

def logged_in():
    return bool(session.get('staff_id'))

def staff_required(function):
    @wraps(function)
    def wrapper(*args, **kwargs):
        if not logged_in():
            flash('Please log in as authorized staff.', 'warning')
            return redirect(url_for('login'))
        return function(*args, **kwargs)
    return wrapper

